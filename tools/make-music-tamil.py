"""
Composes and renders an original background loop in a Tamil / South Indian style.
Everything is generated by this script (no samples, no existing song), so it is original and free to use.

The music:
  - raga Mohanam (a five-note scale of Carnatic music: Sa Ri2 Ga3 Pa Da2), Sa = D
  - adi talam: a cycle of 8 beats, repeated 12 times (about 53 seconds), then the loop starts again
  - instruments imitated with synthesis: bansuri-like flute (with a small "scoop" into notes and a slow
    vibrato), veena-like plucked string, tanpura drone (Sa and Pa), mridangam-like drum
  - form: the flute plays the theme (4 cycles), the veena answers with it (4 cycles),
    then the flute holds long notes over a veena pattern (4 cycles) and comes back to the start

Run (needs Python 3, numpy, scipy and ffmpeg):  python3 tools/make-music-tamil.py
Output: src/assets/music/theme-tamil.mp3
Options: --solo=flute|veena|tanpura|drum  renders one instrument only (to check the notes), --out=<file>
"""
import re, subprocess, sys, os, wave
import numpy as np
from scipy.signal import fftconvolve

SR = 44100
BPM = 108
EIGHTH = 60 / BPM / 2          # one eighth note, in seconds
PER_CYCLE = 16                 # eighths in one cycle of 8 beats
CYCLES = 12
LOOP = int(round(SR * EIGHTH * PER_CYCLE * CYCLES))
SA = 293.66                    # D4
rng = np.random.default_rng(11)  # fixed seed: same result every run

args = dict(a.lstrip('-').split('=') if '=' in a else (a.lstrip('-'), True) for a in sys.argv[1:])
solo = args.get('solo')
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_path = args.get('out') or os.path.join(root, 'src', 'assets', 'music', 'theme-tamil.mp3')

L = np.zeros(LOOP)
R = np.zeros(LOOP)
BUS = {}  # one stereo bus per instrument, so a single instrument can be rendered alone


def bus(name):
    if name not in BUS:
        BUS[name] = [np.zeros(LOOP), np.zeros(LOOP)]
    return BUS[name]


def add(name, sig, start, pan=0.5, gain=1.0):
    """Adds a sound at sample 'start'. What runs past the end wraps to the beginning (seamless loop)."""
    left_gain, right_gain = np.cos(pan * np.pi / 2) * gain, np.sin(pan * np.pi / 2) * gain
    bl, br = bus(name)
    n = len(sig)
    pos = start % LOOP
    done = 0
    while done < n:
        take = min(n - done, LOOP - pos)
        bl[pos:pos + take] += sig[done:done + take] * left_gain
        br[pos:pos + take] += sig[done:done + take] * right_gain
        done += take
        pos = 0


def hz(semitones):
    return SA * 2 ** (semitones / 12)


# ---------- instruments ----------
def flute(semi, dur, vibrato_cents=16, vibrato_hz=5.2):
    """Bansuri-like: mostly fundamental, a little breath noise, a small scoop up into the note, vibrato after a moment."""
    n = int(SR * (dur + 0.25))
    t = np.arange(n) / SR
    f = hz(semi) * np.ones(n)
    f *= 2 ** (-0.8 / 12 * np.clip(1 - t / 0.07, 0, 1))                       # scoop into the note
    ramp = np.clip((t - 0.22) / 0.3, 0, 1)
    f *= 2 ** (vibrato_cents * ramp * np.sin(2 * np.pi * vibrato_hz * t) / 1200)  # vibrato (delayed)
    phase = 2 * np.pi * np.cumsum(f) / SR
    tone = np.sin(phase) + 0.26 * np.sin(2 * phase) + 0.10 * np.sin(3 * phase) + 0.04 * np.sin(4 * phase)
    breath = np.convolve(rng.standard_normal(n), np.ones(5) / 5, mode='same') * 0.10
    env = np.minimum(t / 0.07, 1) * np.clip((dur + 0.12 - t) / 0.14, 0, 1) * (0.85 + 0.15 * np.minimum(t / 0.5, 1))
    return (tone + breath) * env * 0.5


def veena(semi, dur, bend=True):
    """Veena-like plucked string: bright attack, upper harmonics fade faster than the base, long ring."""
    ring = max(dur, 0.9) + 0.6
    n = int(SR * ring)
    t = np.arange(n) / SR
    f = hz(semi) * np.ones(n)
    if bend:
        f *= 2 ** (-0.5 / 12 * np.exp(-t / 0.03))                              # tiny slide into the pitch
    phase = 2 * np.pi * np.cumsum(f) / SR
    out = np.zeros(n)
    for k in range(1, 13):
        out += (1 / k ** 1.05) * np.sin(k * phase + 0.3 * k) * np.exp(-t * (1.1 + 0.55 * k))
    out += 0.25 * np.sin(phase * 1.004) * np.exp(-t * 1.6)                    # slight shimmer
    click = np.convolve(rng.standard_normal(n), np.ones(3) / 3, mode='same') * np.exp(-t / 0.004) * 0.35
    env = np.minimum(t / 0.004, 1)
    return (out + click) * env * 0.55


def tanpura_string(semi, length=3.6):
    """Tanpura drone string: many harmonics, slow shimmering 'buzz' that changes over the note."""
    n = int(SR * length)
    t = np.arange(n) / SR
    f = hz(semi)
    out = np.zeros(n)
    for k in range(1, 22):
        buzz = 0.55 + 0.45 * np.sin(2 * np.pi * (0.35 + 0.07 * k) * t + k)
        out += (1 / k ** 0.9) * buzz * np.sin(2 * np.pi * k * f * t) * np.exp(-t / (3.2 / (1 + 0.08 * k)))
    return out * np.minimum(t / 0.012, 1) * 0.4


def drum(kind):
    """Mridangam-like strokes. thom = deep, tha = ringing slap, ta = light finger tap, ghost = very soft tap."""
    if kind == 'thom':
        n = int(SR * 0.5); t = np.arange(n) / SR
        f = hz(-24) * (1 + 0.35 * np.exp(-t / 0.045))                         # deep tone tuned to Sa, falling a little
        ph = 2 * np.pi * np.cumsum(f) / SR
        return (np.sin(ph) + 0.35 * np.sin(2 * ph)) * np.exp(-t / 0.16) * 0.9
    if kind == 'tha':
        n = int(SR * 0.22); t = np.arange(n) / SR
        noise = np.convolve(rng.standard_normal(n), np.ones(4) / 4, mode='same')
        return (np.sin(2 * np.pi * hz(0) * 1.5 * t) * 0.5 + noise * 0.5) * np.exp(-t / 0.05) * 0.55
    n = int(SR * 0.09); t = np.arange(n) / SR
    noise = np.diff(rng.standard_normal(n + 1))
    amp = 0.30 if kind == 'ta' else 0.12
    return (np.sin(2 * np.pi * hz(12) * t) * 0.4 + noise * 0.5) * np.exp(-t / 0.022) * amp


# ---------- the music ----------
NOTES = {'S': 0, 'R': 2, 'G': 4, 'P': 7, 'D': 9, "S'": 12, "R'": 14, "G'": 16, 'p': -5, 'd': -3}
# Only these five notes (and their octaves) exist in raga Mohanam: S R G P D


def phrase(text):
    """'S2 R1 x4' -> [(semitones or None, length in eighths), ...]. x = rest."""
    out = []
    for token in text.split():
        m = re.fullmatch(r"(x|[SRGPDpd]'?)(\d+)", token)
        assert m, f'bad token {token}'
        out.append((None if m.group(1) == 'x' else NOTES[m.group(1)], int(m.group(2))))
    assert all(n is None or n % 12 in (0, 2, 4, 7, 9) for n, _ in out), f'a note of "{text}" is not in raga Mohanam'
    assert sum(d for _, d in out) == PER_CYCLE, f'cycle "{text}" has {sum(d for _, d in out)} eighths, not {PER_CYCLE}'
    return out


A = [phrase("S2 R1 G1 P2 G1 R1 G2 P1 D1 P2 G2"),
     phrase("D2 P1 D1 S'2 D1 P1 G2 R1 G1 P2 G2"),
     phrase("P1 D1 S'1 R'1 G'2 R'1 S'1 D2 P1 D1 G2 R2"),
     phrase("S'1 D1 P1 G1 R1 G1 R1 S1 S4 x4")]
B = [phrase("P4 D2 S'2 R'4 S'2 D2"),
     phrase("G'4 R'2 S'2 D4 P2 G2"),
     phrase("P2 D2 S'2 R'2 G'4 R'2 S'2"),
     phrase("S'4 D2 P2 G2 R2 S4")]
OSTINATO = [[0, 7, 4, 7, 9, 7, 4, 7] * 2, [0, 4, 7, 9, 7, 4, 2, 4] * 2,
            [0, 7, 12, 7, 9, 7, 4, 7] * 2, [0, 4, 7, 9, 12, 9, 7, 4] * 2]  # veena pattern under the long flute notes

cycle_samples = int(round(SR * EIGHTH * PER_CYCLE))
eighth_samples = SR * EIGHTH


def at(cycle, eighth):
    return int(round(cycle * cycle_samples + eighth * eighth_samples))


for c in range(CYCLES):
    # tanpura: four strings per cycle (Pa, Sa, Sa, low Sa), always present
    for i, semi in enumerate([-17, -5, -5, -12]):
        add('tanpura', tanpura_string(semi), at(c, i * 4), pan=0.5, gain=0.30)

    # drum: adi talam. Beat 1 and 5 deep, beats 3 and 7 slap, light taps between; a roll before each section ends
    soft = 0.6 if c < 2 else 1.0
    for e, kind in [(0, 'thom'), (4, 'tha'), (8, 'thom'), (12, 'tha'), (2, 'ta'), (6, 'ta'), (10, 'ta'), (14, 'ta'),
                    (3, 'ghost'), (7, 'ghost'), (11, 'ghost'), (15, 'ghost')]:
        if c % 4 == 3 and e >= 12:
            continue  # replaced by the roll below
        add('drum', drum(kind), at(c, e), pan=0.5, gain=0.55 * soft)
    if c % 4 == 3:
        for i, kind in enumerate(['tha', 'ta', 'thom', 'ta', 'tha', 'ta', 'tha', 'thom']):  # eight sixteenth notes
            add('drum', drum(kind), at(c, 12 + i * 0.5), pan=0.5, gain=0.5)

    # melody
    if c < 4:
        pos = 0
        for semi, dur in A[c]:
            if semi is not None:
                kamp = 40 if semi == 9 and dur >= 2 else 16  # a wider oscillation on the long Da, like a gamaka
                add('flute', flute(semi, dur * EIGHTH, vibrato_cents=kamp, vibrato_hz=6.2 if semi == 9 else 5.2),
                    at(c, pos), pan=0.58, gain=0.62)
            pos += dur
    elif c < 8:
        pos = 0
        for semi, dur in A[c - 4]:
            if semi is not None:
                add('veena', veena(semi - 12, dur * EIGHTH), at(c, pos), pan=0.40, gain=0.62)
            pos += dur
    else:
        pos = 0
        for semi, dur in B[c - 8]:
            if semi is not None:
                kamp = 40 if semi == 9 and dur >= 2 else 18
                add('flute', flute(semi, dur * EIGHTH, vibrato_cents=kamp, vibrato_hz=6.2 if semi == 9 else 5.4),
                    at(c, pos), pan=0.58, gain=0.60)
            pos += dur
        for i, semi in enumerate(OSTINATO[c - 8]):
            add('veena', veena(semi - 12, EIGHTH * 1.6), at(c, i), pan=0.40, gain=0.40)

# ---------- mix, a little room reverb, loudness ----------
names = [solo] if solo else list(BUS)
if solo:
    assert solo in BUS, f'unknown instrument {solo}; use one of {list(BUS)}'
for name in names:
    L += BUS[name][0]
    R += BUS[name][1]

if not solo:
    # Reverb: noise that fades away, applied to the loop repeated three times and cut out of the middle (keeps the loop seamless)
    n_ir = int(SR * 1.5)
    ir_t = np.arange(n_ir) / SR
    for ch, sig in enumerate((L, R)):
        ir = np.random.default_rng(100 + ch).standard_normal(n_ir) * np.exp(-ir_t / 0.35)
        ir /= np.sqrt(np.sum(ir ** 2))
        wet = fftconvolve(np.tile(sig, 3), ir)[LOOP:2 * LOOP]
        (L if ch == 0 else R)[:] = sig * 0.82 + wet * 0.20

peak = max(np.abs(L).max(), np.abs(R).max())
gain = 0.74 / peak
stereo = np.stack([L * gain, R * gain], axis=1)
pcm = (np.clip(stereo, -1, 1) * 32767).astype('<i2')

wav_path = out_path.rsplit('.', 1)[0] + '.wav'
with wave.open(wav_path, 'wb') as w:
    w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR); w.writeframes(pcm.tobytes())
if solo or out_path.endswith('.wav'):
    print('wrote', wav_path)
else:
    # loudness matched to the other music of the game (about -13.6 LUFS), then mp3
    subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', wav_path, '-af', 'loudnorm=I=-14:TP=-1.5:LRA=7',
                    '-ar', str(SR), '-codec:a', 'libmp3lame', '-b:a', '112k', out_path], check=True)
    os.remove(wav_path)
    print(f'wrote {out_path} ({LOOP / SR:.1f} s, {os.path.getsize(out_path) // 1024} KB)')
