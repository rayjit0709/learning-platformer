"""
Composes and renders the game's background music: an original 16-bar loop
(C - G - Am - F feel, gentle marimba-like melody, soft bass, light percussion).
Everything is generated by this script, so the music is original and free to use.

Run (needs Python 3, numpy and ffmpeg):  python3 tools/make-music.py
Output: src/assets/music/theme.mp3
"""
import subprocess, wave, os
import numpy as np

SR = 44100
BPM = 108
STEP = 60 / BPM / 2          # one eighth note, in seconds
STEPS_PER_BAR = 8
BARS = 16
LOOP_LEN = int(SR * STEP * STEPS_PER_BAR * BARS)
rng = np.random.default_rng(7)  # fixed seed: same result every run

L = np.zeros(LOOP_LEN)
R = np.zeros(LOOP_LEN)

def mix(sig, start, pan=0.5, gain=1.0):
    """Add a sound at 'start' samples. Anything past the loop end wraps to the start (seamless loop)."""
    left, right = sig * gain * (1 - pan) * 1.4142 / 1.4142, sig * gain * pan
    n = len(sig)
    for i in range(0, n, LOOP_LEN):
        seg = slice(i, min(i + LOOP_LEN, n))
        pos = (start + i) % LOOP_LEN
        length = seg.stop - seg.start
        end = pos + length
        if end <= LOOP_LEN:
            L[pos:end] += left[seg]; R[pos:end] += right[seg]
        else:
            first = LOOP_LEN - pos
            L[pos:] += left[seg][:first]; R[pos:] += right[seg][:first]
            L[:end - LOOP_LEN] += left[seg][first:]; R[:end - LOOP_LEN] += right[seg][first:]

def hz(midi): return 440.0 * 2 ** ((midi - 69) / 12)

def pluck(midi, dur, tau=0.30, brightness=0.35):
    """Soft marimba-like note: sine + a little 2nd/4th harmonic, quick attack, exponential decay."""
    n = int(SR * (dur + 4 * tau))
    t = np.arange(n) / SR
    f = hz(midi)
    wave_ = np.sin(2 * np.pi * f * t) + brightness * np.sin(2 * np.pi * 2 * f * t) * np.exp(-t / (tau * 0.5)) \
            + 0.12 * np.sin(2 * np.pi * 4 * f * t) * np.exp(-t / (tau * 0.25))
    env = np.minimum(t / 0.006, 1.0) * np.exp(-t / tau)
    # gentle fade if the note is held shorter than its natural decay
    rel = np.clip((dur + 0.15 - t) / 0.15, 0, 1)
    return wave_ * env * rel * 0.6

def bass_note(midi, dur):
    n = int(SR * (dur + 0.25))
    t = np.arange(n) / SR
    f = hz(midi)
    w = np.sin(2 * np.pi * f * t) + 0.5 * np.sin(2 * np.pi * 2 * f * t) + 0.25 * np.sin(2 * np.pi * 3 * f * t)
    env = np.minimum(t / 0.01, 1.0) * np.exp(-t / 0.35) * np.clip((dur + 0.2 - t) / 0.2, 0, 1)
    return w * env * 0.5

def kick():
    n = int(SR * 0.25); t = np.arange(n) / SR
    f = 50 + 90 * np.exp(-t / 0.03)
    phase = 2 * np.pi * np.cumsum(f) / SR
    return np.sin(phase) * np.exp(-t / 0.07) * 0.7

def hat():
    n = int(SR * 0.08); t = np.arange(n) / SR
    noise = np.diff(rng.standard_normal(n + 1))  # crude high-pass
    return noise * np.exp(-t / 0.018) * 0.35

def clap():
    n = int(SR * 0.14); t = np.arange(n) / SR
    noise = rng.standard_normal(n)
    noise = np.convolve(noise, np.ones(6) / 6, mode='same')  # a little softer than a hat
    return noise * np.exp(-t / 0.04) * 0.45

def pad(midis, dur):
    n = int(SR * (dur + 0.6)); t = np.arange(n) / SR
    out = np.zeros(n)
    for m in midis:
        out += np.sin(2 * np.pi * hz(m) * t) + 0.3 * np.sin(2 * np.pi * hz(m) * 1.003 * t)
    env = np.minimum(t / 0.35, 1.0) * np.clip((dur + 0.5 - t) / 0.5, 0, 1)
    return out * env / len(midis)

# ---- the music itself -------------------------------------------------
# Scale used for the melody (C major pentatonic, MIDI notes). Index = scale degree.
S = [60, 62, 64, 67, 69, 72, 74, 76, 79, 81, 84]
N = None  # rest

CHORDS = {  # bass note, arpeggio notes
    'C':  (48, [55, 60, 64]),
    'G':  (43, [55, 59, 62]),
    'Am': (45, [57, 60, 64]),
    'F':  (41, [57, 60, 65]),
}
PROGRESSION = ['C', 'G', 'Am', 'F', 'C', 'G', 'Am', 'F',
               'F', 'C', 'G', 'Am', 'F', 'C', 'G', 'C']

MELODY = [  # one list of 8 eighth-notes per bar (index into S, or None for a rest)
    [5, 7, 8, 7, 5, 6, 5, N], [4, 5, 6, 5, 4, 3, 4, N], [5, 6, 7, 8, 9, 8, 7, N], [8, 7, 5, 7, 6, 5, 4, N],
    [5, 7, 8, 9, 8, 7, 8, N], [6, 7, 8, 7, 6, 5, 6, N], [9, 8, 7, 5, 7, 8, 9, N], [8, N, 7, N, 5, N, 4, N],
    [4, N, 5, 7, N, 5, 4, N], [5, 7, 8, N, 7, 5, N, N], [6, 8, 9, N, 8, 6, N, N], [9, 8, 7, 8, 9, N, 8, N],
    [8, 9, 8, 7, 5, 7, 8, N], [7, 8, 10, 8, 7, 5, 7, N], [6, 5, 4, 3, 4, 5, 6, N], [5, N, N, N, N, N, N, N],
]

bar_len = STEP * STEPS_PER_BAR
for bar, name in enumerate(PROGRESSION):
    bass_midi, arp = CHORDS[name]
    t0 = bar * bar_len
    # soft pad under the whole bar
    mix(pad([m - 12 if m > 60 else m for m in arp], bar_len), int(t0 * SR), pan=0.5, gain=0.10)
    for step in range(STEPS_PER_BAR):
        ts = int((t0 + step * STEP) * SR)
        # arpeggio, panned a little left
        pattern = [0, 1, 2, 1, 0, 1, 2, 1]
        mix(pluck(arp[pattern[step]], STEP * 1.1, tau=0.22, brightness=0.2), ts, pan=0.38, gain=0.30)
        # bass on beats 1 and 3
        if step in (0, 4):
            mix(bass_note(bass_midi, STEP * 3), ts, pan=0.5, gain=0.55)
            mix(kick(), ts, pan=0.5, gain=0.35)
        # light percussion
        if step in (2, 6):
            mix(clap(), ts, pan=0.5, gain=0.10)
        if step % 2 == 1:
            mix(hat(), ts, pan=0.6, gain=0.08)
        # melody, panned a little right
        idx = MELODY[bar][step]
        if idx is not None:
            length = 1
            while step + length < STEPS_PER_BAR and MELODY[bar][step + length] is None:
                length += 1
            if bar == BARS - 1:
                length = 6  # the last note rings out
            mix(pluck(S[idx], STEP * min(length, 3), tau=0.34), ts, pan=0.58, gain=0.62)

# ---- finish: soft limiter, normalise, write mp3 ------------------------
stereo = np.stack([L, R], axis=1)
stereo = np.tanh(stereo * 1.2) / np.tanh(1.2)
stereo *= 0.8 / np.max(np.abs(stereo))
pcm = (stereo * 32767).astype('<i2')

os.makedirs('src/assets/music', exist_ok=True)
tmp = 'theme.wav'
with wave.open(tmp, 'wb') as f:
    f.setnchannels(2); f.setsampwidth(2); f.setframerate(SR); f.writeframes(pcm.tobytes())
subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', tmp, '-codec:a', 'libmp3lame', '-b:a', '112k',
                'src/assets/music/theme.mp3'], check=True)
os.remove(tmp)
print(f'Wrote src/assets/music/theme.mp3  ({LOOP_LEN / SR:.1f} s loop, {BARS} bars at {BPM} BPM)')
